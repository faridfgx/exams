// Flat list: [{ lastName, firstName, fullName, className }, ...]
const students = Object.entries(classesData).flatMap(([className, list]) =>
  list.map(([lastName, firstName]) => ({
    lastName,
    firstName,
    fullName: `${lastName} ${firstName}`,
    className
  }))
);

// Helpers
function getStudentsByClass(className) {
  return students.filter(s => s.className === className);
}

function findStudent(query) {
  return students.filter(s => s.fullName.includes(query));
}

// Export for Node.js (ignored in the browser)
if (typeof module !== "undefined" && module.exports) {
  module.exports = { classesData, students, getStudentsByClass, findStudent };
}

